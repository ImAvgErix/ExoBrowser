// Exo Browser's icons are Exo's (Tabler, drawn by brand/icons.tsx's rules). This writes the glyphs
// src/browser/icons.tsx names into src/browser/glyphs.ts, as scripts/icons.mjs does for Exo:
// npm run icons (check-only with --check).
import fs from 'node:fs'
import path from 'node:path'
import tabler from '@iconify-json/tabler/icons.json' with { type: 'json' }
import info from '@iconify-json/tabler/info.json' with { type: 'json' }

const dir = path.resolve(import.meta.dirname, '../src/browser')
const source = fs.readFileSync(path.join(dir, 'icons.tsx'), 'utf8')
const out = path.join(dir, 'glyphs.ts')

// glyph('star', 'star'): the glyph each name draws, and its -filled where Tabler has one.
const names = new Set()
for (const [, name] of source.matchAll(/glyph\('[^']+', '([a-z0-9-]+)'\)/g)) {
  if (!tabler.icons[name]) throw new Error(`Tabler has no glyph "${name}"`)
  names.add(name)
  if (!name.endsWith('-filled') && tabler.icons[`${name}-filled`]) names.add(`${name}-filled`)
}

const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1]
const parts = name => {
  const body = tabler.icons[name].body
  const group = body.startsWith('<g') ? body.slice(0, body.indexOf('>') + 1) : ''
  const list = []
  for (const [tag] of body.matchAll(/<path[^>]*\/>/g)) {
    const fill = (attr(tag, 'fill') ?? attr(group, 'fill') ?? 'currentColor') === 'currentColor'
    const stroke = (attr(tag, 'stroke') ?? attr(group, 'stroke') ?? 'none') === 'currentColor'
    if (fill || stroke) list.push([stroke ? (fill ? 2 : 0) : 1, attr(tag, 'd')])
  }
  const shapes = body.replace(/<\/?g[^>]*>/g, '').replace(/<path[^>]*\/>/g, '')
  if (shapes || !list.length) throw new Error(`${name}: only paths are read (${body.slice(0, 80)})`)
  return list
}

const lines = [...names].sort().map(name => `  '${name}': ${JSON.stringify(parts(name))},`)
const next = `// Generated by scripts/browser-icons.mjs from ${info.name} ${info.version} (${info.author.name}, ${info.license.spdx}): the
// glyphs browser/icons.tsx draws, on Tabler's ${tabler.width} grid; each path is drawn by its line (0), filled (1) or both (2).
// Don't edit; run npm run icons:browser.
export const GLYPHS = {
${lines.join('\n')}
} as const satisfies Record<string, readonly (readonly [0 | 1 | 2, string])[]>
`
const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
if (process.argv.includes('--check')) {
  if (next !== current) { console.error('browser/glyphs.ts is out of date; run npm run icons:browser'); process.exit(1) }
} else if (next !== current) fs.writeFileSync(out, next)
console.log(`${names.size} glyphs`)
